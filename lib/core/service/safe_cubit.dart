import 'package:flutter_bloc/flutter_bloc.dart';

/// كيوبت لا يرمي حين تُغلق شاشته قبل أن يعود ردّ الشبكة.
///
/// نمط كل كيوبت في التطبيق واحد: ينتظر الشبكة ثم يُصدر حالة.
///
/// ```dart
/// final response = await repo.fetch();   // ← المستخدم يخرج هنا
/// emit(Loaded(response));                // ← فيُستدعى على كيوبت مُغلَق
/// ```
///
/// وbloc يرمي عندها `Cannot emit new states after calling close` من مسار
/// غير متزامن **لا يلتقطه أحد**، فيُسقط الإطار لا الشاشة وحدها. وقع هذا
/// فعلاً في «تفاصيل الرحلة»: خروج سريع من نتائج البحث قبل وصول الرد.
///
/// ولا يقع في كل مرة — يحتاج أن يسبق الإغلاقُ وصولَ الردّ — فيظهر
/// متقطّعاً ويصعب تكراره، وهو أسوأ ما في العيوب.
///
/// كان العلاج `if (isClosed) return;` قبل كل `emit` يلي `await`. لكنه
/// سطر يُنسى في كل دالة جديدة، وفحصُ المشروع وجد **16 ملفاً** أُغفل فيها.
/// الوراثة تُغلق الباب مرة واحدة: كل ما هو قائم وكل ما سيُكتب.
///
/// **الابتلاع مقصود:** `emit` بعد الإغلاق ليس حالة تستحق الانهيار — هو
/// نتيجة طبيعية لمستخدم غادر الشاشة، ولا شيء ينتظر تلك الحالة أصلاً.
class SafeCubit<T> extends Cubit<T> {
  SafeCubit(super.initialState);

  @override
  void emit(T state) {
    if (isClosed) return;
    super.emit(state);
  }
}
