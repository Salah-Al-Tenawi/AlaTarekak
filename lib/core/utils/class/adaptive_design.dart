import 'dart:ui' show Size;

/// مقاس التصميم المكافئ للشاشة الحالية — **حدٌّ لتضخّم الأجهزة العريضة**.
///
/// `flutter_screenutil` يقيس كل شيء بنسبة عرض الشاشة إلى عرض التصميم:
/// `.sp` و`.w` و`.h` و`.r` جميعاً. ومقاس التصميم كان مثبَّتاً على عرض
/// هاتف (375)، فعلى تابلت عرضه 800 صارت النسبة **2.13** — أي أن كل خطّ
/// وكل حشوة تُضاعَف مرّتين. ولهذا كبر كل شيء دفعةً واحدة: الحجوزات
/// والرحلات ونقاط الثقة والمحادثة والأشرطة، لا شاشةً بعينها.
///
/// الحلّ هنا **يقلب المعادلة**: بدل تثبيت مقاس التصميم وترك النسبة تكبر
/// بلا حدّ، نُثبّت سقفاً للنسبة ونشتقّ منه مقاس التصميم. فالهاتف يبقى
/// كما هو تماماً (نسبته دون السقف أصلاً)، والتابلت يكبر قليلاً — لأن
/// الشاشة الأكبر تُقرأ من مسافة أبعد فتستحقّ زيادةً يسيرة، لا ضِعفاً.
///
/// **دالّة نقيّة** تُختبر بلا شجرة واجهة.

/// مقاس التصميم الأصلي — ما رُسمت عليه الشاشات كلها.
const Size kBaseDesignSize = Size(375, 812);

/// أقصى تكبير مسموح مهما اتّسعت الشاشة.
///
/// خمس عشرة بالمئة: زيادةٌ تُلحظ ولا تُثقل. والسقف يقع فعلياً عند عرض
/// ‎431 بكسل منطقياً — أي أن كل الهواتف تحته، وأكبرها يبلغه ولا يتجاوزه.
const double kMaxDesignScale = 1.15;

/// مقاس التصميم الذي يجعل نسبة `flutter_screenutil` لا تتجاوز
/// [kMaxDesignScale].
///
/// [screen] مقاس الشاشة بالبكسل المنطقي.
Size adaptiveDesignSize(
  Size screen, {
  Size base = kBaseDesignSize,
  double maxScale = kMaxDesignScale,
}) {
  if (screen.width <= 0 || screen.height <= 0) return base;

  final rawScale = screen.width / base.width;

  // شاشة أضيق من التصميم: تُترك كما هي — التصغير مطلوب لا محدود
  if (rawScale <= maxScale) return base;

  // النسبة تُثبَّت عند السقف، فيُشتقّ منها مقاس التصميم
  return Size(screen.width / maxScale, screen.height / maxScale);
}
