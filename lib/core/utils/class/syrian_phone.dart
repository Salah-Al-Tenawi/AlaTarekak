/// أرقام الهاتف السورية — قبولاً وتطبيعاً.
///
/// المستخدم يكتب رقمه بالصيغة التي يحفظها: `0988626577` أو
/// `+963988626577` أو `00963988626577`، وقد يفصل بمسافات أو شُرَط.
/// لكن الخادم يفرض `^09\d{8}$` ويرفض ما عداه بـ 422 — بما فيه صيغة
/// المفتاح الدولي.
///
/// فالقبول واسع والإرسال ضيّق: تُقبل كل الصيغ في الواجهة ثم تُطبَّع إلى
/// الصيغة التي يفهمها الخادم قبل الإرسال. رفضُ رقم صحيح لأن المستخدم
/// كتب مفتاح بلده ليس تحقّقاً بل عرقلة.
class SyrianPhone {
  SyrianPhone._();

  /// شبكات الهاتف المحمول السورية تبدأ بـ 9 بعد الصفر.
  static final _local = RegExp(r'^09\d{8}$');

  /// يُرجع الرقم بصيغة `09XXXXXXXX`، أو null إن لم يكن رقماً سورياً صالحاً.
  static String? normalize(String? input) {
    if (input == null) return null;

    // تُحذف المسافات والشُرَط والأقواس، ويُحوَّل بادئ 00 إلى +
    var s = input.trim().replaceAll(RegExp(r'[\s\-()]'), '');
    if (s.startsWith('00')) s = '+${s.substring(2)}';

    if (s.startsWith('+963')) {
      s = '0${s.substring(4)}';
    } else if (s.startsWith('963') && s.length == 12) {
      // 963988626577 — بلا + ولا 00
      s = '0${s.substring(3)}';
    } else if (s.startsWith('9') && s.length == 9) {
      // 988626577 — كتبه بلا الصفر
      s = '0$s';
    }

    return _local.hasMatch(s) ? s : null;
  }

  static bool isValid(String? input) => normalize(input) != null;

  /// رسالة الخطأ الموحّدة — تذكر الصيغتين المقبولتين لا صيغة واحدة.
  static const error =
      'رقم غير صالح — اكتبه هكذا 0988626577 أو +963988626577';
}
